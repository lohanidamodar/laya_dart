// Pins the ONNX Runtime release that hook/build.dart bundles.
//
// Usage: dart run tool/pin_ort.dart
//
// 1. Reads the GitHub release for v1.30.0 and takes each CPU archive's
//    download URL and sha256 (GitHub's `digest` field; an asset without one is
//    downloaded and hashed instead). An archive the release lacks is listed
//    as not bundled.
// 2. Writes hook/ort_release.dart, a const table keyed by (os, arch), and
//    prints it with the archive sizes for review.
// 3. Downloads the win-x64 archive into .tooling/ort/ (verified against the
//    pin) and extracts include/onnxruntime_c_api.h, plus the
//    onnxruntime_error_code.h it includes, there. They are the reference for
//    lib/src/inference/ort/ort_api.dart and are not committed.
import 'dart:convert';
import 'dart:io';

import '../hook/ort_fetch.dart';

const _version = '1.30.0';

// (os, arch) as package:code_assets names them -> the archive's platform tag
// and the shared library's path inside it.
const _targets = [
  ('windows', 'x64', 'win-x64', '.zip', 'lib/onnxruntime.dll'),
  ('windows', 'arm64', 'win-arm64', '.zip', 'lib/onnxruntime.dll'),
  ('linux', 'x64', 'linux-x64', '.tgz', 'lib/libonnxruntime.so.$_version'),
  (
    'linux',
    'arm64',
    'linux-aarch64',
    '.tgz',
    'lib/libonnxruntime.so.$_version',
  ),
  ('macos', 'arm64', 'osx-arm64', '.tgz', 'lib/libonnxruntime.$_version.dylib'),
  ('macos', 'x64', 'osx-x86_64', '.tgz', 'lib/libonnxruntime.$_version.dylib'),
];

Future<Map<String, Object?>> _getJson(Uri url) async {
  final client = HttpClient();
  try {
    final request = await client.getUrl(url);
    request.headers.set('Accept', 'application/vnd.github+json');
    request.headers.set('User-Agent', 'laya_server-pin_ort');
    final response = await request.close();
    final body = await response.transform(utf8.decoder).join();
    if (response.statusCode != 200) {
      throw HttpException('GET $url -> ${response.statusCode}: $body');
    }
    return jsonDecode(body) as Map<String, Object?>;
  } finally {
    client.close();
  }
}

Future<void> main() async {
  final release = await _getJson(
    Uri.parse(
      'https://api.github.com/repos/microsoft/onnxruntime/releases/tags/v$_version',
    ),
  );
  final assets = {
    for (final a
        in (release['assets']! as List<Object?>).cast<Map<String, Object?>>())
      a['name']! as String: a,
  };

  final rows = <String>[];
  final missing = <String>[];
  final sizes = <String, int>{};
  for (final (os, arch, tag, ext, lib) in _targets) {
    final stem = 'onnxruntime-$tag-$_version';
    final asset = assets['$stem$ext'];
    if (asset == null) {
      missing.add('$stem$ext ($os-$arch)');
      continue;
    }
    final url = asset['browser_download_url']! as String;
    sizes['$stem$ext'] = asset['size']! as int;
    var digest = asset['digest'] as String?;
    if (digest == null || !digest.startsWith('sha256:')) {
      stdout.writeln('no sha256 digest for $stem$ext; downloading to hash it');
      final file = File('.tooling/ort/$stem$ext');
      digest = 'sha256:${await _downloadAndHash(Uri.parse(url), file)}';
    }
    rows.add(
      "  ('$os', '$arch'): (\n"
      "    url: '$url',\n"
      "    sha256: '${digest.substring('sha256:'.length)}',\n"
      "    lib: '$stem/$lib',\n"
      '  ),',
    );
  }

  final source = StringBuffer()
    ..writeln(
      '// GENERATED by tool/pin_ort.dart from the GitHub release v$_version.',
    )
    ..writeln('// Do not edit by hand; rerun the tool to repin.')
    ..writeln()
    ..writeln('/// The pinned ONNX Runtime release.')
    ..writeln("const ortVersion = '$_version';")
    ..writeln()
    ..writeln(
      '/// CPU release archives by (os, arch), named as package:code_assets',
    )
    ..writeln('/// names them: the download URL, its sha256, and the shared')
    ..writeln("/// library's path inside the archive.")
    ..writeln(
      'const ortRelease = <(String, String), ({String url, String sha256, String lib})>{',
    )
    ..writeAll(rows, '\n')
    ..writeln()
    ..writeln('};');
  if (missing.isNotEmpty) {
    source
      ..writeln()
      ..writeln('// Not published for v$_version, so not bundled:')
      ..writeAll(missing.map((m) => '//   $m'), '\n')
      ..writeln();
  }
  File('hook/ort_release.dart').writeAsStringSync(source.toString());
  stdout
    ..writeln(source)
    ..writeln('archive sizes:')
    ..writeAll(sizes.entries.map((e) => '  ${e.key}: ${e.value} bytes'), '\n')
    ..writeln();
  if (missing.isNotEmpty) {
    stdout.writeln('MISSING from the release: ${missing.join(', ')}');
  }

  // The C API header, from the verified win-x64 archive.
  final win = assets['onnxruntime-win-x64-$_version.zip']!;
  final winDigest = (win['digest']! as String).substring('sha256:'.length);
  final archive = await downloadVerified(
    Uri.parse(win['browser_download_url']! as String),
    File('.tooling/ort/onnxruntime-win-x64-$_version.zip'),
    winDigest,
  );
  // onnxruntime_error_code.h holds OrtErrorCode, which the C API header includes.
  for (final header in ['onnxruntime_c_api.h', 'onnxruntime_error_code.h']) {
    extractEntry(
      archive,
      'onnxruntime-win-x64-$_version/include/$header',
      File('.tooling/ort/$header'),
    );
    stdout.writeln('wrote .tooling/ort/$header');
  }
}

Future<String> _downloadAndHash(Uri url, File file) async {
  file.parent.createSync(recursive: true);
  final client = HttpClient();
  try {
    final response = await (await client.getUrl(url)).close();
    if (response.statusCode != 200) {
      throw HttpException('GET $url -> ${response.statusCode}', uri: url);
    }
    await response.pipe(file.openWrite());
  } finally {
    client.close();
  }
  return sha256OfFile(file);
}
