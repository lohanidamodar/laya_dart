// Pins the files of the three onnx-community checkpoints.
//
// Usage: dart run tool/pin_models.dart
//
// 1. Reads each checkpoint's Hugging Face tree at its pinned revision
//    (CheckpointSpec.onnxRepo / onnxRevision).
// 2. Takes the sha256 of every LFS file from the tree's `lfs.oid`. The model
//    graphs and their `.onnx_data` sidecars are LFS, so none is downloaded.
//    A non-LFS file (config.json, a small tokenizer.json) is downloaded and
//    hashed; identical git blobs are downloaded once. A `.onnx` or
//    `.onnx_data` file without an LFS oid is an error, never downloaded.
// 3. Writes lib/src/store/pins.g.dart and prints the table for review.
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:laya_server/src/model/checkpoint.dart' show CheckpointSpec;

const _wanted = [
  'tokenizer.json',
  'config.json',
  'onnx/model.onnx',
  'onnx/model.onnx_data',
  'onnx/model_fp16.onnx',
  'onnx/model_fp16.onnx_data',
];

Future<Object?> _getJson(HttpClient client, Uri url) async {
  final res = await (await client.getUrl(url)).close();
  if (res.statusCode != 200) {
    throw StateError('GET $url -> ${res.statusCode}');
  }
  return jsonDecode(await utf8.decodeStream(res));
}

Future<String> _hash(HttpClient client, Uri url) async {
  final res = await (await client.getUrl(url)).close();
  if (res.statusCode != 200) {
    throw StateError('GET $url -> ${res.statusCode}');
  }
  final digest = await sha256.bind(res).first;
  return digest.toString();
}

Future<void> main() async {
  final client = HttpClient();
  final byBlob = <String, String>{};
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/pin_models.dart. Do not edit.')
    ..writeln()
    ..writeln("import 'model_store.dart';")
    ..writeln()
    ..writeln('/// Every pinned file of each checkpoint, both variants.')
    ..writeln('const Map<String, List<PinnedFile>> pinnedFiles = {');
  for (final spec in CheckpointSpec.all.values) {
    final repo = spec.onnxRepo;
    final rev = spec.onnxRevision;
    final tree =
        await _getJson(
              client,
              Uri.parse(
                'https://huggingface.co/api/models/$repo/tree/$rev'
                '?recursive=true',
              ),
            )
            as List<Object?>;
    final byPath = {
      for (final e in tree.cast<Map<String, Object?>>())
        if (e['type'] == 'file') e['path']! as String: e,
    };
    out.writeln("  '${spec.name}': [");
    stdout.writeln('${spec.name} ($repo @ ${rev.substring(0, 12)})');
    for (final path in _wanted) {
      final e = byPath[path] ?? (throw StateError('$repo has no $path'));
      final size = e['size']! as int;
      final lfs = e['lfs'] as Map<String, Object?>?;
      final String sha;
      if (lfs != null) {
        sha = lfs['oid']! as String;
        if (lfs['size'] != size) throw StateError('$repo $path: size differs');
      } else if (path.contains('.onnx')) {
        throw StateError('$repo $path is not LFS; refusing to download it');
      } else {
        sha = byBlob[e['oid']! as String] ??= await _hash(
          client,
          Uri.parse('https://huggingface.co/$repo/resolve/$rev/$path'),
        );
      }
      out.writeln(
        "    PinnedFile('$repo', '$rev', '$path', $size,\n"
        "        '$sha'),",
      );
      stdout.writeln(
        '  ${path.padRight(28)} ${size.toString().padLeft(11)} '
        '${sha.substring(0, 12)}${lfs == null ? ' (hashed)' : ''}',
      );
    }
    out.writeln('  ],');
  }
  out.writeln('};');
  client.close();
  File('lib/src/store/pins.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('wrote lib/src/store/pins.g.dart');
}
